#!/usr/bin/env python3
"""Turn a GIF of your Muse into Meta's status-screen sprite (avatar/happy_anim.c + .h in the gadget SDK).

    python3 gadget/port/gen_avatar_anim.py assets/avatar/typing/muse-typing-240.gif --cells 60 --step 2 --preview /tmp/anim.png

The SDK's status screen scales each "art pixel" (cell) up to a LCD_ANIM_SCALE square (5 on the 4" board), so a
240 px GIF sampled at 60x60 cells draws 300x300 on the 320x480 panel. Index 0 of the palette is the background:
pixels near the GIF's own background colour (its top-left pixel) map to it, and --bg sets what colour that is on
screen (default black). Frames must share one duration; --step keeps every Nth frame. Palette is capped at 256.
Writes gadget/port/avatar/happy_anim.c and happy_anim.h; gadget/port/apply.py copies them into the SDK clone.
"""
import argparse, pathlib, sys
from PIL import Image

def rgb565_be(rgb):
    r, g, b = rgb; v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return ((v & 0xFF) << 8) | (v >> 8)

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("gif"); ap.add_argument("--cells", type=int, default=60)
    ap.add_argument("--step", type=int, default=1); ap.add_argument("--frame-ms", type=int, default=0)
    ap.add_argument("--bg", default="000000", help="on-screen background colour (hex)"); ap.add_argument("--key", type=int, default=40, help="distance from the GIF background that still counts as background")
    ap.add_argument("--colors", type=int, default=64, help="palette size (quantized)"); ap.add_argument("--preview")
    ap.add_argument("--out", default=str(pathlib.Path(__file__).resolve().parent / "avatar"))
    a = ap.parse_args()
    gif = Image.open(a.gif); W = H = a.cells; src_w, src_h = gif.size; cell_w, cell_h = src_w / W, src_h / H
    frames_rgb = []; durations = []
    for i in range(0, gif.n_frames, max(1, a.step)):
        gif.seek(i); durations.append(gif.info.get("duration", 100)); frames_rgb.append(gif.convert("RGB").copy())
    bgpx = frames_rgb[0].getpixel((0, 0)); bg = tuple(int(a.bg[i:i+2], 16) for i in (0, 2, 4))
    # One shared palette: quantize a contact sheet of all frames, then sample cell centres.
    sheet = Image.new("RGB", (src_w * len(frames_rgb), src_h))
    for i, f in enumerate(frames_rgb): sheet.paste(f, (i * src_w, 0))
    q = sheet.quantize(colors=max(2, a.colors - 1), method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert("RGB")
    palette = {bg: 0}; frames = []
    for i in range(len(frames_rgb)):
        cells = []
        for y in range(H):
            for x in range(W):
                sx = int(i * src_w + (x + 0.5) * cell_w); sy = int((y + 0.5) * cell_h)
                raw = frames_rgb[i].getpixel((int((x + 0.5) * cell_w), sy)); c = q.getpixel((sx, sy))
                if sum(abs(raw[k] - bgpx[k]) for k in range(3)) <= a.key: cells.append(0); continue
                cells.append(palette.setdefault(c, len(palette)))
        frames.append(cells)
    if len(palette) > 256: sys.exit(f"{len(palette)} colours; lower --colors")
    ms = a.frame_ms or max(set(durations), key=durations.count)
    out = pathlib.Path(a.out); out.mkdir(parents=True, exist_ok=True)
    c = ["// Status-screen sprite generated by gadget/port/gen_avatar_anim.py from " + pathlib.Path(a.gif).name + ". Do not edit.",
         '#include "happy_anim.h"', "", "#if CONFIG_HOMEHUB_DISPLAY", "", f"const uint16_t happy_anim_palette[{len(palette)}] = {{"]
    for col in palette: c.append(f"    0x{rgb565_be(col):04x},  // #{col[0]:02x}{col[1]:02x}{col[2]:02x}")
    c += ["};", "", "const uint8_t happy_anim_frames[HAPPY_ANIM_FRAMES][HAPPY_ANIM_HEIGHT * HAPPY_ANIM_WIDTH] = {"]
    for fr in frames:
        c.append("    {" + ",".join(str(v) for v in fr) + "},")
    c += ["};", "", "#endif", ""]
    (out / "happy_anim.c").write_text("\n".join(c))
    (out / "happy_anim.h").write_text("#pragma once\n#include <stdint.h>\n#include \"sdkconfig.h\"\n"
        f"#define HAPPY_ANIM_WIDTH     {W}\n#define HAPPY_ANIM_HEIGHT    {H}\n#define HAPPY_ANIM_FRAMES    {len(frames)}\n#define HAPPY_ANIM_FRAME_MS  {ms}\n"
        f"#if CONFIG_HOMEHUB_DISPLAY\nextern const uint16_t happy_anim_palette[{len(palette)}];\n"
        "extern const uint8_t happy_anim_frames[HAPPY_ANIM_FRAMES][HAPPY_ANIM_HEIGHT * HAPPY_ANIM_WIDTH];\n#endif\n")
    print(f"wrote {out}/happy_anim.c: {len(frames)} frames of {W}x{H} cells, {len(palette)} colours, {ms} ms/frame, {len(frames)*W*H//1024} KB")
    if a.preview:
        cols = list(palette); S = 3; n = min(len(frames), 8); sheet = Image.new("RGB", (W * S * n, H * S))
        for i in range(n):
            for y in range(H):
                for x in range(W):
                    col = cols[frames[i][y * W + x]]
                    for dy in range(S):
                        for dx in range(S): sheet.putpixel((i * W * S + x * S + dx, y * S + dy), col)
        sheet.save(a.preview); print("preview", a.preview)

if __name__ == "__main__":
    main()
